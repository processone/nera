-module(atomics_integer_domain).
-export([test/0]).
test() ->
    A = atomics:new(1, []),
    ok = atomics:put(A, 1, 1152921504606846975),
    1152921504606846976 = atomics:add_get(A, 1, 1),
    1152921504606846976 = atomics:get(A, 1),
    ok = atomics:put(A, 1, -1152921504606846976),
    -1152921504606846977 = atomics:sub_get(A, 1, 1),
    -1152921504606846977 = atomics:exchange(A, 1, 9223372036854775807),
    -9223372036854775808 = atomics:add_get(A, 1, 1),
    9223372036854775807 = atomics:sub_get(A, 1, 1),
    9223372036854775807 = atomics:compare_exchange(A, 1, 0, 1),
    ok = atomics:compare_exchange(A, 1, 9223372036854775807, -9223372036854775808),
    #{min := -9223372036854775808, max := 9223372036854775807} = atomics:info(A),
    bad(fun() -> atomics:put(A, 1, 9223372036854775808) end),
    -9223372036854775808 = atomics:get(A, 1),
    U = atomics:new(1, [{signed, false}]),
    ok = atomics:put(U, 1, 18446744073709551615),
    18446744073709551615 = atomics:get(U, 1),
    0 = atomics:add_get(U, 1, 1),
    18446744073709551615 = atomics:sub_get(U, 1, 1),
    18446744073709551615 = atomics:exchange(U, 1, 9223372036854775808),
    9223372036854775808 = atomics:compare_exchange(U, 1, 0, 1),
    ok = atomics:compare_exchange(U, 1, 9223372036854775808, 0),
    #{min := 0, max := 18446744073709551615} = atomics:info(U),
    bad(fun() -> atomics:put(U, 1, -1) end),
    bad(fun() -> atomics:put(U, 1, 18446744073709551616) end),
    0 = atomics:get(U, 1),
    ok = atomics:add(U, 1, 18446744073709551615),
    18446744073709551615 = atomics:get(U, 1),
    ok = atomics:sub(U, 1, -18446744073709551615),
    18446744073709551614 = atomics:get(U, 1),
    bad(fun() -> atomics:add(U, 1, -9223372036854775809) end),
    bad(fun() -> atomics:sub(U, 1, 9223372036854775809) end),
    18446744073709551614 = atomics:get(U, 1),
    bad(fun() -> atomics:new(1, [{signed, nope}]) end),
    bad(fun() -> atomics:new(1, [unknown]) end),
    bad(fun() -> atomics:new(1, [signed | wrong_tail]) end),
    ok.
bad(F) -> {'EXIT', {badarg, _}} = (catch F()), ok.
