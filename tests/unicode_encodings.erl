%% EXPECT: unicode_encodings_ok
%% Expected values are OTP 29 results for unicode:characters_to_binary/2,3 and
%% characters_to_list/1,2 (Cowlib calls these with latin1/utf8 conversions).
-module(unicode_encodings).
-export([test/0]).

check(Got, Expected) when Got =:= Expected -> ok;
check(Got, Expected) -> erlang:error({mismatch, Got, Expected}).

badarg(F) ->
    try F() of
        Other -> erlang:error({no_badarg, Other})
    catch
        error:badarg -> ok
    end.

test() ->
    check(unicode:characters_to_binary([300,$a], latin1, utf8),
          {error,<<>>,[300,97]}),
    check(unicode:characters_to_binary(<<233,$a>>, latin1, utf8),
          <<195,169,97>>),
    check(unicode:characters_to_binary([<<233>>,$a,300], latin1),
          {error,<<195,169,97>>,[300]}),
    check(unicode:characters_to_binary(<<"é"/utf8,$a>>, utf8, latin1),
          <<233,97>>),
    check(unicode:characters_to_binary(<<"a€b"/utf8>>, utf8, latin1),
          {error,<<97>>,<<226,130,172,98>>}),
    check(unicode:characters_to_binary([$a,16#20ac,$b], utf8, latin1),
          {error,<<97>>,[[8364],98]}),
    check(unicode:characters_to_binary([<<"a"/utf8>>,16#20ac,<<"b"/utf8>>], utf8, latin1),
          {error,<<97>>,[[8364],<<98>>]}),
    check(unicode:characters_to_binary("aé", unicode, utf16),
          <<0,97,0,233>>),
    check(unicode:characters_to_binary([16#1f600], utf8, {utf16,little}),
          <<61,216,0,222>>),
    check(unicode:characters_to_binary([16#1f600], utf8, utf32),
          <<0,1,246,0>>),
    check(unicode:characters_to_binary(<<0,97,0,98>>, utf16, utf8),
          <<97,98>>),
    check(unicode:characters_to_binary(<<97,0,98>>, {utf16,little}, utf8),
          {incomplete,<<97>>,<<98>>}),
    check(unicode:characters_to_binary(<<216,0,0,97>>, utf16, utf8),
          {error,<<>>,<<216,0,0,97>>}),
    check(unicode:characters_to_binary(<<216,0>>, utf16, utf8),
          {incomplete,<<>>,<<216,0>>}),
    check(unicode:characters_to_binary(<<220,0,0,97>>, utf16, utf8),
          {error,<<>>,<<220,0,0,97>>}),
    check(unicode:characters_to_binary(<<0,0,0,97,0,0>>, utf32, utf8),
          {incomplete,<<97>>,<<0,0>>}),
    check(unicode:characters_to_binary(<<0,17,0,0>>, utf32, utf8),
          {error,<<>>,<<0,17,0,0>>}),
    check(unicode:characters_to_binary([<<0,97>>,<<0,98>>,$c], utf16, utf8),
          <<97,98,99>>),
    check(unicode:characters_to_binary([<<0>>,<<97>>], utf16, utf8),
          <<97>>),
    check(unicode:characters_to_binary(<<"a"/utf8>>, latin1, latin1),
          <<97>>),
    check(unicode:characters_to_binary(<<"aé"/utf8>>, utf8, utf8),
          <<97,195,169>>),
    check(unicode:characters_to_list(<<"aé€"/utf8>>),
          [97,233,8364]),
    check(unicode:characters_to_list(<<"aé"/utf8>>, latin1),
          [97,195,169]),
    check(unicode:characters_to_list(<<"a",195>>, utf8),
          {incomplete,[97],<<195>>}),
    check(unicode:characters_to_list(<<"a",255>>, utf8),
          {error,[97],<<255>>}),
    check(unicode:characters_to_list([$a,<<195>>,<<169>>,[16#20ac]], utf8),
          [97,233,8364]),
    check(unicode:characters_to_list([$a,16#d800], utf8),
          {error,[97],[55296]}),
    check(unicode:characters_to_list(<<0,97,216,0>>, utf16),
          {incomplete,[97],<<216,0>>}),
    check(unicode:characters_to_list(<<>>, utf8),
          []),
    check(unicode:characters_to_list(<<1,2,3>>, utf32),
          {error,[],<<1,2,3>>}),
    check(unicode:characters_to_list(<<0,0,216,0>>, utf32),
          {error,[],<<0,0,216,0>>}),
    check(unicode:characters_to_list(<<0,0,0,97,0,0,0,98>>, {utf32,big}),
          [97,98]),
    check(unicode:characters_to_binary(<<0,0,216>>, utf32, utf8),
          {error,<<>>,<<0,0,216>>}),
    check(unicode:characters_to_binary(<<0,17>>, utf32, utf8),
          {error,<<>>,<<0,17>>}),
    check(unicode:characters_to_binary(<<0,16>>, utf32, utf8),
          {incomplete,<<>>,<<0,16>>}),
    check(unicode:characters_to_binary(<<0,0,216,0>>, utf32, utf8),
          {error,<<>>,<<0,0,216,0>>}),
    check(unicode:characters_to_binary(<<0>>, {utf32,little}, utf8),
          {incomplete,<<>>,<<0>>}),
    check(unicode:characters_to_binary(<<0,0,0>>, {utf32,little}, utf8),
          {incomplete,<<>>,<<0,0,0>>}),
    check(unicode:characters_to_binary(<<0,0,17>>, {utf32,little}, utf8),
          {error,<<>>,<<0,0,17>>}),
    check(unicode:characters_to_binary(<<0,220>>, utf16, utf8),
          <<195,156>>),
    check(unicode:characters_to_binary(<<216>>, utf16, utf8),
          {incomplete,<<>>,<<216>>}),
    check(unicode:characters_to_binary(<<216,0,220>>, utf16, utf8),
          {incomplete,<<>>,<<216,0,220>>}),
    check(unicode:characters_to_binary(<<216,0,0>>, utf16, utf8),
          {error,<<>>,<<216,0,0>>}),
    check(unicode:characters_to_binary(<<216,0,216,0>>, utf16, utf8),
          {error,<<>>,<<216,0,216,0>>}),
    check(unicode:characters_to_binary([<<"a€b"/utf8>>,$c], utf8, latin1),
          {error,<<97>>,[<<226,130,172,98>>,99]}),
    check(unicode:characters_to_binary([$a,[$b,16#20ac,$d],$e], utf8, latin1),
          {error,<<97,98>>,[[[8364],100],101]}),
    check(unicode:characters_to_binary([$a|<<"€"/utf8>>], utf8, latin1),
          {error,<<97>>,<<226,130,172>>}),
    check(unicode:characters_to_binary([<<"a€"/utf8>>|<<"€"/utf8>>], utf8, latin1),
          {error,<<97>>,[<<226,130,172>>|<<226,130,172>>]}),
    check(unicode:characters_to_binary([16#20ac], utf8, latin1),
          {error,<<>>,[[8364]]}),
    check(unicode:characters_to_binary([16#20ac|<<"b">>], utf8, latin1),
          {error,<<>>,[[8364]|<<98>>]}),
    check(unicode:characters_to_binary([[16#20ac]], utf8, latin1),
          {error,<<>>,[[[8364]]]}),
    check(unicode:characters_to_binary([16#d800], utf8, utf16),
          {error,<<>>,[[55296]]}),
    check(unicode:characters_to_binary([16#d800,$a], latin1, utf16),
          {error,<<>>,[[55296],97]}),
    check(unicode:characters_to_binary(<<237,160,128>>, utf8, utf16),
          {error,<<>>,<<237,160,128>>}),
    check(unicode:characters_to_binary([<<237,160,128>>, $a], utf8, utf16),
          {error,<<>>,[<<237,160,128>>,97]}),
    check(unicode:characters_to_binary([$a,<<195>>,[<<169>>]], utf8, latin1),
          <<97,233>>),
    check(unicode:characters_to_binary([$a,<<195>>], utf8, latin1),
          {incomplete,<<97>>,<<195>>}),
    check(unicode:characters_to_binary([$a,<<195>>,$b], utf8, latin1),
          {error,<<97>>,[<<195>>,98]}),
    check(unicode:characters_to_binary(<<"aé"/utf8>>, utf8, utf16),
          <<0,97,0,233>>),
    check(unicode:characters_to_binary(<<"a"/utf8, 195>>, utf8, utf16),
          {incomplete,<<0,97>>,<<195>>}),
    check(unicode:characters_to_binary(<<97,233,0>>, latin1, {utf32,little}),
          <<97,0,0,0,233,0,0,0,0,0,0,0>>),
    check(unicode:characters_to_binary([<<216>>,<<0>>,<<220,0>>], utf16, utf8),
          <<240,144,128,128>>),
    check(unicode:characters_to_binary([<<216>>,<<0>>,<<0,97>>], utf16, utf8),
          {error,<<>>,[<<216,0,0,97>>,<<>>]}),
    check(unicode:characters_to_list([16#10ffff, 16#110000], utf8),
          {error,[1114111],[1114112]}),
    check(unicode:characters_to_list([300], latin1),
          {error,[],[300]}),
    check(unicode:characters_to_list(["é", <<"é"/utf8>>], latin1),
          [233,195,169]),
    check(unicode:characters_to_list(["é", <<"é"/utf8>>], utf8),
          [233,233]),
    check(unicode:characters_to_list([<<"é"/utf8>>, 16#20ac, "x"], utf8),
          [233,8364,120]),
    check(unicode:characters_to_binary(<<"é"/utf8>>, utf8, utf16),
          <<0,233>>),
    %% Unknown or malformed encodings and non-chardata raise badarg.
    badarg(fun() -> unicode:characters_to_binary(<<"a">>, foo, utf8) end),
    badarg(fun() -> unicode:characters_to_binary(<<"a">>, utf8, {utf8, big}) end),
    badarg(fun() -> unicode:characters_to_binary(<<"a">>, {utf16, middle}, utf8) end),
    badarg(fun() -> unicode:characters_to_binary(foo, utf8, utf8) end),
    badarg(fun() -> unicode:characters_to_list(abc, utf8) end),
    badarg(fun() -> unicode:characters_to_list(<<1>>, bad) end),
    badarg(fun() -> unicode:characters_to_list(<<1:1>>, utf8) end),
    badarg(fun() -> unicode:characters_to_list([a], latin1) end),
    %% The same calls through apply and a variable module and function.
    M = unicode, F = characters_to_binary,
    check(apply(M, F, [<<233>>, latin1, utf8]), <<195,169>>),
    check(erlang:apply(unicode, characters_to_list, [<<195,169>>, utf8]), [233]),
    check((fun unicode:characters_to_list/2)(<<233>>, latin1), [233]),
    io:format("unicode_encodings_ok~n").
