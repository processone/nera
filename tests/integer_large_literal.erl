-module(integer_large_literal).
-export([test/0]).
-define(LARGE, 99999999999999999999).
-define(TEXT(X), ??X).
-ifdef(TEST).
inactive() -> 999999999999999999999999999999999999999999.
-endif.

test() ->
    B = binary_to_integer(<<"99999999999999999999">>),
    B = ?LARGE,
    "99999999999999999999" = ?TEXT(99999999999999999999),
    B = 16#56BC75E2D630FFFFF,
    9223372036854775808 = binary_to_integer(<<"9223372036854775808">>),
    -9223372036854775808 = binary_to_integer(<<"-9223372036854775808">>),
    -9223372036854775809 = binary_to_integer(<<"-9223372036854775809">>),
    Huge = 12345678901234567890123456789012345678901234567890,
    Huge = binary_to_integer(<<"12345678901234567890123456789012345678901234567890">>),
    <<170,248,60,161,80,38,116,122,248,199,241,150,206,63,10,210>> = <<Huge:128>>,
    negative = classify(-99999999999999999999),
    positive = classify(B),
    other = classify(B + 1),
    true = guarded(B),
    false = guarded(B + 1),
    yes = case B of 99999999999999999999 -> yes; _ -> no end,
    true = is_integer(B),
    yes = literal_case(),
    <<1>> = <<-99999999999999999999:8>>,
    100000000000000000000 = B + 1,
    #{99999999999999999999 := value} = #{B => value},
    <<1>> = <<18446744073709551617:8>>,
    <<128,0,0,0,0,0,0,1>> = <<9223372036854775809:64>>,
    <<1,0,0,0,0,0,0,128>> = <<9223372036854775809:64/little>>,
    <<0,192>> = <<0:1,9223372036854776065:9/little,0:6>>,
    <<0,0>> = <<0:1,18446744073709551616:9,0:6>>,
    ok.

classify(-99999999999999999999) -> negative;
classify(99999999999999999999) -> positive;
classify(_) -> other.

guarded(B) when B =:= 99999999999999999999 -> true;
guarded(_) -> false.

literal_case() ->
    case 99999999999999999999 of
        99999999999999999999 -> yes;
        _ -> no
    end.
