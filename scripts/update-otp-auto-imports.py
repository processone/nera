#!/usr/bin/env python3
"""Derive the name catalogue from OTP 29.0.4's erl_internal abstract code.

End users do not need OTP. Maintainers run this with the pinned OTP installed;
--check verifies the committed catalogue without changing it.
"""
import argparse
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
query = r'''
{ok,V}=file:read_file(filename:join([code:root_dir(),"releases","29","OTP_VERSION"])),
"29.0.4"=string:trim(binary_to_list(V)),
{ok,{_,[{abstract_code,{raw_abstract_v1,Forms}}]}}=
 beam_lib:chunks(code:which(erl_internal),[abstract_code]),
L=lists:usort([{F,A} || {function,_,bif,2,Cs}<-Forms,
 {clause,_,[{atom,_,F},{integer,_,A}],_,_}<-Cs]),
[begin true=erl_internal:bif(F,A), io:format("    (\"~s\", ~B),~n",[F,A]) end || {F,A}<-L],
halt().
'''
entries = subprocess.check_output(["erl", "+S", "1", "-noshell", "-eval", query], text=True)
content = ('//! OTP 29.0.4 auto-import names, independent of native availability.\n'
           '//! Generated by scripts/update-otp-auto-imports.py from erl_internal:bif/2.\n'
           '//! Upstream: https://github.com/erlang/otp/tree/OTP-29.0.4/lib/stdlib/src/erl_internal.erl\n\n'
           'pub const OTP_AUTO_IMPORTS: &[(&str, u32)] = &[\n' + entries + '];\n')
path = root / "crates/nera-ir/src/otp_auto_imports.rs"
if args.check:
    if path.read_text() != content:
        raise SystemExit("OTP catalogue differs; run scripts/update-otp-auto-imports.py")
    print("OTP 29.0.4 catalogue equals erl_internal:bif/2")
else:
    path.write_text(content)
